typedef enum {
    TS_NORMAL = 0,
    TS_BLOCK_COMMENT,
    TS_TRIPLE_SINGLE,
    TS_TRIPLE_DOUBLE,
} ts_mode_t;

typedef struct {
    hl_lang_t          lang;
    const kw_set_t    *kw;
    const lang_syntax_t *syn;
    ts_mode_t           mode;
} hl_state_t;

void *hl_state_new(hl_lang_t lang) {
    if (lang == HL_LANG_NONE) return NULL;
    hl_state_t *s = calloc(1, sizeof(*s));
    if (!s) return NULL;
    s->lang = lang;
    s->kw   = kw_for_lang(lang);
    s->syn  = syn_for_lang(lang);
    s->mode = TS_NORMAL;
    return s;
}

void hl_state_free(void *state) {
    free(state);
}

