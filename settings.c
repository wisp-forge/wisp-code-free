typedef struct {
    int row;
    int col;
    int width;
    int height;
} box_t;

static void compute_box(box_t *b) {
    int rows = tui_rows();
    int cols = tui_cols();

    b->height = ROW_COUNT + 6;
    if (b->height > rows - 2) b->height = rows - 2;

    b->width = 74;
    if (b->width > (cols * 9) / 10) b->width = (cols * 9) / 10;
    if (b->width < 40) b->width = 40;

    b->row = (rows - b->height) / 2;
    if (b->row < 1) b->row = 1;
    b->col = (cols - b->width) / 2;
    if (b->col < 1) b->col = 1;
}

