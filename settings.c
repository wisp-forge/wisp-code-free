/* ================================================================== */
/*  Local monotonic clock                                             */
/* ================================================================== */

static long long settings_monotonic_ms(void) {
    struct timespec t;
    clock_gettime(CLOCK_MONOTONIC, &t);
    return (long long)t.tv_sec * 1000LL + t.tv_nsec / 1000000LL;
}

